function assertSvg(name, svg) {
  for (const required of ['<svg ', 'viewBox="', '<title ', '<desc ']) {
    if (!svg.includes(required)) throw new Error(`${name}: missing ${required}`);
  }
  if (/NaN|Infinity|width="XXX"|<script\b|<foreignObject\b|\bhref="https?:/i.test(svg)) {
    throw new Error(`${name}: invalid or externally dependent SVG content`);
  }
}

function runSelfTests() {
  const zero = progressModel(0, 13);
  const complete = progressModel(13, 13);
  const partial = progressModel(1, 13);
  const unknown = progressModel(0, 0);
  if (zero.displayPercent !== '0.0%' || boundedFill(1100, zero) !== 0) throw new Error('zero-progress self-test failed');
  if (complete.displayPercent !== '100.0%' || boundedFill(1100, complete) !== 1100 || complete.status !== 'COMPLETE') throw new Error('complete self-test failed');
  if (partial.displayPercent !== '7.7%' || !(boundedFill(700, partial) > 0 && boundedFill(700, partial) < 700)) throw new Error('partial self-test failed');
  if (unknown.displayPercent !== 'N/A' || unknown.fraction !== null || boundedFill(700, unknown) !== 0) throw new Error('unknown-scope self-test failed');
  const longScope = makeCard(progressModel(1, 13)).replace(scopeLabel, 'A deliberately long measured scope label used to prove bounded card geometry without changing the viewBox');
  assertSvg('long-scope fixture', longScope);
}

runSelfTests();
if (args.has('--self-test')) {
  console.log(JSON.stringify({ schema: 'swir.progress-svg-pro/1.0', selfTest: true, valid: true }));
  process.exit(0);
}

const model = readRoadmapModel();
const outputs = new Map([
  [cardPath, makeCard(model)],
  [miniPath, makeMini(model)],
  [templatePath, makeTemplate()],
]);

for (const [filePath, svg] of outputs) assertSvg(path.basename(filePath), svg);

if (args.has('--check')) {
  for (const [filePath, expected] of outputs) {
    if (!fs.existsSync(filePath)) fail(`missing generated asset: ${path.relative(root, filePath)}`);
    const actual = fs.readFileSync(filePath, 'utf8');
    if (actual !== expected) fail(`stale generated asset: ${path.relative(root, filePath)}; run node scripts/generate-readme-progress.mjs`);
  }
} else {
  fs.mkdirSync(path.dirname(cardPath), { recursive: true });
  for (const [filePath, svg] of outputs) fs.writeFileSync(filePath, svg, 'utf8');
}

console.log(JSON.stringify({
  schema: 'swir.progress-svg-pro/1.0',
  source: path.basename(roadmapPath),
  scope: scopeLabel,
  calculation: 'verified_completed / total_in_scope',
  completed: model.completed,
  total: model.total,
  percent: model.percent === null ? null : Number(model.percent.toFixed(1)),
  status: model.status,
  mode: args.has('--check') ? 'check' : 'write',
  valid: true,
}));
