function fail(message) {
  console.error(`PROGRESS SVG FAIL: ${message}`);
  process.exit(1);
}

function escapeXml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');
}

function progressModel(completed, total) {
  if (!Number.isInteger(completed) || completed < 0) throw new Error('completed must be a non-negative integer');
  if (!Number.isInteger(total) || total < 0) throw new Error('total must be a non-negative integer');
  if (total === 0) {
    return { completed, total, fraction: null, percent: null, displayPercent: 'N/A', status: 'PLANNING' };
  }
  if (completed > total) throw new Error('completed cannot exceed total');
  const fraction = completed / total;
  const percent = fraction * 100;
  return {
    completed,
    total,
    fraction,
    percent,
    displayPercent: `${percent.toFixed(1)}%`,
    status: completed === total ? 'COMPLETE' : 'IN PROGRESS',
  };
}

function boundedFill(trackWidth, model) {
  if (model.fraction === null || model.fraction <= 0) return 0;
  return Math.min(trackWidth, Math.max(0, trackWidth * model.fraction));
}

function formatNumber(value) {
  if (!Number.isFinite(value)) throw new Error('non-finite SVG geometry');
  return value.toFixed(3).replace(/\.0+$|(?<=\.[0-9]*?)0+$/g, '').replace(/\.$/, '');
}

function readRoadmapModel() {
  const text = fs.readFileSync(roadmapPath, 'utf8');
  const start = text.indexOf('## Version roadmap');
  const end = text.indexOf('## Development rule', start);
  if (start < 0 || end <= start) fail('canonical Version roadmap scope is missing');
  const checklist = text.slice(start, end);
  const matches = [...checklist.matchAll(/^- \[(x| )\] .+$/gm)];
  if (matches.length === 0) fail('canonical roadmap has no measurable checklist items');
  const completed = matches.filter(match => match[1] === 'x').length;
  return progressModel(completed, matches.length);
}

function fillRect(x, y, width, height, radius, clipId) {
  if (width <= 0) return '';
  return `<rect x="${x}" y="${y}" width="${formatNumber(width)}" height="${height}" rx="${radius}" fill="url(#progressGradient)" clip-path="url(#${clipId})" filter="url(#softGlow)"/>`;
}

